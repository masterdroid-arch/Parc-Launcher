    @Test fun allSixLegacyFilesKeepTheirCompleteValues() {
        assertEquals(6, expected.size)
        for (golden in expected) {
            val actual = SkinJson.decode(File("src/main/assets/skins/${golden.id}.json").readText())
            assertEquals(golden.id, golden, actual)
            assertEquals("", actual.typography.numeralFamily)
            // T162: only Midnight and Dusk have a lighter card; the other four keep the derived default.
            if (golden.id != "midnight" && golden.id != "dusk") assertEquals(actual.colors.surface, actual.colors.moduleSurface)
            assertEquals(actual.colors.lineActive, actual.colors.moduleGuide)
            assertEquals(actual.colors.textPrimary, actual.colors.moduleInk)
            assertEquals(ModuleStyle.solid, actual.shape.moduleStyle)
            assertEquals(20f, actual.shape.tileCornerDp)
            assertEquals(32f, actual.shape.moduleCornerDp)
            assertTrue(golden.id, SkinSafety.readable(actual))
        }
    }
