package com.brightblu.parc.model

import com.brightblu.parc.model.fakes.*
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking

/** Host assertions for the public contract and the shared fixtures, without a test framework. */
fun main() = runBlocking {
    val app = AppId("example/example.Main@0")
    val otherUser = AppId("example/example.Main@10")
    check(app != otherUser)
    val folder = FolderId("social")
    val arc = ArcSpec("A1", 0, 120f, 180f, 270f, 4, Layer.Home)
    val slots = mapOf(0 to Slot.App(app), 1 to Slot.Folder(folder),
        2 to Slot.Action(ActionKind.Settings), 3 to Slot.Link("https://example.com/123", "Help"))
    val layout = ParcLayout(arcs = listOf(ArcAssignment(arc, slots)),
        folders = listOf(Folder(folder, "Social", setOf("friends"), listOf(app))),
        pins = setOf(app), hidden = setOf(otherUser))
    check(LayoutJson.decode(LayoutJson.encode(layout)) == layout)
    check(runCatching { LayoutJson.decode("{\"version\":2}") }.isFailure)
    check(runCatching { LayoutJson.decode("{\"unknown\":true}") }.isFailure)
    for (skin in listOf(Skin.Midnight, Skin.Dusk)) {
        check(SkinJson.decode(SkinJson.encode(skin)) == skin)
        check(skin.colors.bg == 0xFF000000)
        check(skin.motion.durSnap == 320)
    }
    check(runCatching { SkinJson.decode(SkinJson.encode(Skin.Midnight)
        .replace("\"id\":", "\"unknown\":0,\"id\":")) }.isFailure)
    check(runCatching { Skin.Midnight.copy(motionScale = 2f) }.isFailure)
    val legacySkin = """{"id":"old","name":"Old","colors":{"bg":4278190080,"lineBase":4280956228,"lineActive":4282010206,"accent":4286551240,"glow":1199559880,"textPrimary":4293323504,"textSecondary":4287403942,"pulse":4289259514,"danger":4293227371,"scrim":3087007744,"surface":4278519560}}"""
    val old = SkinJson.decode(legacySkin)
    check(old.colors.accent2 == old.colors.accent)
    check(old.colors.warn == 0xFFFFB000L)
    check(old.depthScale == listOf(1f, 0.94f, 0.88f, 0.82f))
    check(old.depthAlpha == listOf(1f, 0.96f, 0.90f, 0.84f))
    check(old.parallaxDp == 6f && old.hud.monospace)
    check(runCatching { old.copy(depthScale = listOf(1f)) }.isFailure)
    check(runCatching { old.copy(depthAlpha = listOf(1f, 1f, Float.NaN, 1f)) }.isFailure)
    check(runCatching { old.copy(parallaxDp = 7f) }.isFailure)
    check(runCatching { HudTokens(bracketWidthDp = -1f) }.isFailure)
    check(Metrics.keepOutTopDp == 56f && Metrics.keepOutRightDp == 48f)
    check(Metrics.keepOutBottomDp == 56f && Metrics.minSlotPitchDp == 60f)
    val noSearch = RingState(listOf(arc), emptyList(), 0f)
    check(noSearch.highlight == null)
    check(noSearch.copy(highlight = emptySet()).highlight?.isEmpty() == true)
    val repo: LayoutRepository = FakeLayoutRepository(layout)
    repo.hide(app)
    repo.hide(app)
    check(repo.layout.value.hidden == setOf(app, otherUser))
    check(repo.layout.value.arcs == layout.arcs && repo.layout.value.pins == layout.pins)
    check(LayoutJson.decode(repo.exportLayout()).hidden == setOf(app, otherUser))
    repo.unhide(app)
    repo.unhide(app)
    check(repo.layout.value == layout)
    repo.move(SlotPosition("A1", 0), SlotPosition("A1", 3))
    check(repo.layout.value.arcs.single().slots[3] == Slot.App(app))
    repo.unpin(app)
    check(app !in repo.layout.value.pins)
    repo.pin(app, SlotPosition("A1", 0))
    check(app in repo.layout.value.pins)
    val created = FolderId("new")
    repo.createFolder(created, "New")
    repo.renameFolder(created, "Renamed")
    repo.addToFolder(created, app)
    check(repo.layout.value.folders.last().appIds == listOf(app))
    repo.removeFromFolder(created, app)
    check(repo.layout.value.folders.last().appIds.isEmpty())
    repo.importLayout(LayoutJson.encode(layout))
    check(LayoutJson.decode(repo.exportLayout()) == layout)
    check(runCatching { repo.move(SlotPosition("missing", 0), SlotPosition("A1", 0)) }.isFailure)
    val usage: UsageRepository = FakeUsageRepository(mapOf(folder to listOf(app)))
    usage.recordLaunch(app); usage.recordLaunch(otherUser); usage.recordLaunch(app)
    check(usage.recents(2).first() == listOf(app, otherUser))
    check(usage.rank(folder) == listOf(app))
    val index = FakeAppIndex(listOf(AppEntry(app, "Example", "example", false, 0)))
    index.launch(app)
    check(index.launches == listOf(app) && index.apps.value.single().id == app)
    check(index.icon(app, 112) == null && index.shortcuts(app).isEmpty())
    val hit = SearchHit(app, 1.0, listOf(MatchRange(0, 2)))
    check(FakeSearchEngine(listOf(hit)).query("ex") == listOf(hit))
    val notifications = FakeNotificationState()
    notifications.setUnread(mapOf("example" to 2))
    check(notifications.unread.value["example"] == 2)
    val skins = FakeSkinProvider()
    skins.setSkin(Skin.Dusk)
    check(skins.active.value == Skin.Dusk)
    val renderer: RingRenderer = FakeRingRenderer()
    check(renderer is FakeRingRenderer)
    val callbacks = FakeRingCallbacks()
    val slotHit = SlotHit(SlotPosition("A1", 0), Slot.App(app), 100f, 200f)
    callbacks.onTap(slotHit); callbacks.onLongPress(slotHit)
    callbacks.onDrag(slotHit, DragPhase.End)
    check(callbacks.tap == slotHit && callbacks.longPress == slotHit)
    check(callbacks.drag == slotHit to DragPhase.End)
    check(noSearch.aim == null)
    callbacks.onAim(slotHit.position)
    check(callbacks.aim == slotHit.position && callbacks.aimCount == 1)
    println("T01 contract assertions passed: JSON, tokens, service fixtures, renderer boundary")
}
